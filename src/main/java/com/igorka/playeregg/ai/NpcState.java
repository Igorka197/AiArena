package com.igorka.playeregg.ai;

/**
 * Состояния конечного автомата (FSM).
 * LLM только ВЫБИРАЕТ состояние и цель; исполнение идёт локально каждый тик.
 */
public enum NpcState {
	/** Стоять неподвижно. */
	IDLE,
	/** Идти к точке (навигация ведёт сама, без запросов к API). */
	GOTO,
	/** Следовать за игроком: цель пересчитывается каждый тик локально. */
	FOLLOW,
	/** Патрулирование/исследование: точки выбираются локально. */
	PATROL,
	/** Бой: преследование и удары мгновенно в каждом тике. */
	COMBAT,
	/** Добыча блока: подход + прогрессивное разрушение с анимацией. */
	MINE,
	/** Установка блока. */
	BUILD,
	/** Поиск ресурса поблизости (сканирование чанка локально). */
	SEEK_RESOURCE
}
